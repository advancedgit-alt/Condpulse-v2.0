CREATE OR REPLACE FUNCTION cp.current_tenant() RETURNS uuid LANGUAGE sql STABLE AS $$
 SELECT NULLIF(current_setting('app.tenant_id',true),'')::uuid;
$$;
CREATE OR REPLACE FUNCTION cp.current_actor() RETURNS uuid LANGUAGE sql STABLE AS $$
 SELECT NULLIF(current_setting('app.actor_id',true),'')::uuid;
$$;
REVOKE ALL ON FUNCTION cp.current_tenant(), cp.current_actor() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION cp.current_tenant(), cp.current_actor() TO cp_api,cp_worker;
